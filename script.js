// ==UserScript==
// @name         GitHub AI Audit Script
// @namespace    https://github.com/
// @version      14.0
// @description  Deep checks repo for AI presence. Displays a simple, unified red banner if any AI traces are found.
// @match        https://github.com/*
// @grant        GM_xmlhttpRequest
// @connect      api.github.com
// ==/UserScript==

(function() {
    'use strict';

    const AI_ENTITY_FLEX = /(?:[@\/]|\b|^)(claude(?:-code)?|copilot|cursor|chatgpt|devin|coderabbit|sweep(?:-|[bot])|cody|cline|roo-cline|windsurf|aider|bolt-new|v0-dev|gpt-engineer)(?:\b|[\s\/]|$)/i;
    const COMMIT_SIG_PATTERNS = /(co-authored-by:.*(copilot|cursor|claude|chatgpt|devin|cody|cline|aider|windsurf)|generated by (cursor|copilot|claude|cody|continue|devin|v0)|impacted by ai|aicommits|cursor-agent|copilot-swe)/i;
    const REPO_TEXT_AI_PATTERNS = /(100% ai(-generated)?|autonomous agent|coded (entirely )?by (claude|cursor|devin|cline|v0)|generated by (v0|claude|chatgpt)|built with (cursor|claude|copilot|v0|bolt|aider)|created (using|with) (ai|chatgpt|claude|cursor))/i;

    const AGENT_CONFIGS = [
        { regex: /^agents\.md$/i, name: 'AI Agent Context' },
        { regex: /^claude\.md$/i, name: 'Claude Code' },
        { regex: /^\.clinerules/i, name: 'Cline' },
        { regex: /^\.windsurf(rules)?/i, name: 'Windsurf' },
        { regex: /^\.cursor(rules)?$/i, name: 'Cursor Rules' },
        { regex: /^\.cursorignore$/i, name: 'Cursor Ignore' },
        { regex: /^\.claude$/i, name: 'Claude Code Config' },
        { regex: /^copilot-instructions\.md$/i, name: 'GitHub Copilot' },
        { regex: /^\.aider(ignore|conf\.yml)?$/i, name: 'Aider' },
        { regex: /^\.continue/i, name: 'Continue.dev' },
        { regex: /^mcp\.json$/i, name: 'Model Context Protocol' }
    ];

    let scannedRepo = '';
    const scriptLogs = [];

    function escapeHtml(unsafe) {
        return (unsafe || '').toString()
        .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;").replace(/'/g, "&#039;");
    }

    function addLog(message, isDebug = false) {
        const time = new Date().toLocaleTimeString('en-US', { hour12: false, hour: "numeric", minute: "numeric", second: "numeric" });
        const entry = `[${time}] ${message}`;
        scriptLogs.push(entry);

        if (isDebug) {
            console.log(`%c[GitHub AI Audit Script DEBUG]%c ${message}`, 'color: #9e9e9e;', 'color: inherit;');
        } else {
            console.log(`%c[GitHub AI Audit Script]%c ${message}`, 'color: #fb8c00; font-weight: bold;', 'color: inherit;');
        }
        updateLogModal();
    }

    function getRepoInfo() {
        const parts = window.location.pathname.split('/').filter(Boolean);
        if (parts.length >= 2) {
            const reserved = ['settings', 'marketplace', 'explore', 'topics', 'trending', 'notifications', 'login', 'orgs', 'sponsors'];
            if (!reserved.includes(parts[0])) {
                return { owner: parts[0], repo: parts[1], isRoot: parts.length === 2 || (parts.length === 4 && parts[2] === 'tree') };
            }
        }
        return null;
    }

    // --- UI INJECTIONS ---

    function toggleLogModal() {
        let modal = document.getElementById('gh-ai-log-modal');
        if (modal) {
            modal.style.display = modal.style.display === 'none' ? 'flex' : 'none';
        } else {
            modal = document.createElement('div');
            modal.id = 'gh-ai-log-modal';
            modal.style.cssText = `
            position: fixed; bottom: 24px; right: 24px; width: 600px; max-width: 90vw; height: 450px;
            background: #0d1117; border: 1px solid #30363d; border-radius: 8px; z-index: 99999;
            display: flex; flex-direction: column; box-shadow: 0 8px 24px rgba(0,0,0,0.8);
            font-family: ui-monospace, SFMono-Regular, "SF Mono", Menlo, Consolas, "Liberation Mono", monospace;
            `;

            modal.innerHTML = `
            <div style="padding: 10px 14px; border-bottom: 1px solid #30363d; display: flex; justify-content: space-between; align-items: center; background: #161b22; border-radius: 8px 8px 0 0;">
            <strong style="color: #c9d1d9; font-size: 13px; font-family: sans-serif;">Scanner Verbose Logs</strong>
            <button id="gh-ai-log-close" style="background: none; border: none; color: #8b949e; cursor: pointer; font-size: 16px;">&times;</button>
            </div>
            <div id="gh-ai-log-content" style="flex: 1; overflow-y: auto; padding: 12px; font-size: 11px; color: #8b949e; white-space: pre-wrap; word-wrap: break-word;"></div>
            `;
            document.body.appendChild(modal);
            document.getElementById('gh-ai-log-close').onclick = () => modal.style.display = 'none';
            updateLogModal();
        }
    }

    function updateLogModal() {
        const content = document.getElementById('gh-ai-log-content');
        if (content) {
            content.innerHTML = scriptLogs.join('\n');
            content.scrollTop = content.scrollHeight;
        }
    }

    function renderBanner(reasons) {
        let banner = document.getElementById('gh-ai-detected-banner');
        if (banner) banner.remove();

        const color = '#e53935'; // Always red
        const label = 'AI TRACES DETECTED';

        banner = document.createElement('div');
        banner.id = 'gh-ai-detected-banner';
        banner.style.cssText = `
        background: #0d1117; border: 1px solid ${color}; color: #c9d1d9;
        padding: 16px 20px; margin: 18px auto; max-width: 860px; width: 92%;
        border-radius: 8px; box-sizing: border-box; font-family: -apple-system, sans-serif;
        font-size: 13px; line-height: 1.5; box-shadow: 0 4px 16px rgba(0, 0, 0, 0.45);
        `;

        const target = document.querySelector('#repo-content-turbo-frame') || document.querySelector('#repo-content-pjax-container') || document.querySelector('main');

        const items = reasons.map(r => `
        <li style="margin-bottom: 8px;">
        <span style="font-size: 11px; padding: 2px 6px; border-radius: 3px; background: rgba(255,255,255,0.1); margin-right: 8px; font-weight: 600; color: #fff;">${r.category}</span>
        <strong style="color: #fff;">${r.title}:</strong> <span style="color: #8b949e;">${r.detail}</span>
        </li>
        `).join('');

        banner.innerHTML = `
        <div style="display:flex; justify-content:space-between; margin-bottom: 14px; border-bottom: 1px solid #30363d; padding-bottom: 12px; align-items: center;">
        <div style="display:flex; align-items:center; gap:12px;">
        <span style="background:${color}; color:#fff; font-size:11px; padding:4px 8px; border-radius:4px; font-weight:800; letter-spacing: 0.5px;">${label}</span>
        </div>
        <div style="display:flex; align-items:center; gap:10px;">
        <button id="gh-ai-log-inline-btn" style="background:rgba(255,255,255,0.06); border:1px solid #444; color:#aaa; cursor:pointer; font-size:11px; padding:4px 8px; border-radius:4px; transition: 0.2s;">View Verbose Logs</button>
        </div>
        </div>
        <ul style="margin:0; padding-left:18px; color: ${color};">${items}</ul>
        `;

        if (target) target.prepend(banner);
        document.getElementById('gh-ai-log-inline-btn').addEventListener('click', toggleLogModal);
        addLog(`Banner rendered.`);
    }

    // --- SCANNERS ---

    function fetchAPI(endpoint) {
        return new Promise((resolve) => {
            GM_xmlhttpRequest({
                method: 'GET',
                url: `https://api.github.com/${endpoint}`,
                headers: { 'Accept': 'application/vnd.github.v3+json', 'User-Agent': 'Violentmonkey-AI-Auditor' },
                onload: (res) => {
                    if (res.status === 403 || res.status === 429) {
                        addLog(`[ERROR] API Rate Limited on ${endpoint}.`, false);
                        resolve(null);
                    } else if (res.status >= 200 && res.status < 300) {
                        addLog(`[SUCCESS] Fetched API: ${endpoint}`, true);
                        resolve(JSON.parse(res.responseText));
                    } else {
                        addLog(`[WARN] API returned ${res.status} for ${endpoint}`, false);
                        resolve(null);
                    }
                },
                onerror: () => {
                    addLog(`[ERROR] Network error fetching ${endpoint}`, false);
                    resolve(null);
                }
            });
        });
    }

    function pollDOMForBots() {
        addLog('--- STARTING ASYNC DOM POLL (2.5 seconds) ---', false);
        return new Promise((resolve) => {
            const found = new Set();
            let attempts = 0;
            const maxAttempts = 5;

            const interval = setInterval(() => {
                attempts++;
                const elements = document.querySelectorAll('img, a[data-hovercard-type], a[data-hovercard-url], span.author');
                let nodesEvaluated = 0;

                elements.forEach(node => {
                    if (node.closest('#gh-ai-log-modal') || node.closest('#gh-ai-detected-banner')) return;

                    nodesEvaluated++;
                    const alt = node.getAttribute('alt') || '';
                    const href = node.getAttribute('href') || '';
                    const text = node.textContent || '';
                    const aria = node.getAttribute('aria-label') || '';

                    const str = `${alt} ${href} ${text} ${aria}`.toLowerCase();
                    const match = str.match(AI_ENTITY_FLEX);

                    if (match && !['github'].includes(match[1])) {
                        found.add(match[1]);
                    }
                });

                addLog(`[DEBUG] Poll attempt ${attempts}: Evaluated ${nodesEvaluated} safe DOM nodes.`, true);

                if (attempts >= maxAttempts) {
                    clearInterval(interval);
                    addLog(`[DEBUG] DOM Polling finished. Unique bots found in UI: ${found.size}`, true);
                    resolve(Array.from(found));
                }
            }, 500);
        });
    }

    function scanDocumentationText() {
        addLog('--- STARTING DOM TEXT SCAN ---', false);
        const hits = [];
        const descEl = document.querySelector('p.f4.my-3, [data-testid="repository-description"]');
        const descText = descEl ? descEl.textContent.trim() : '';
        const topics = Array.from(document.querySelectorAll('a.topic-tag')).map(t => t.textContent.trim()).join(' ');

        const metaText = `${descText} ${topics}`;
        const readmeEl = document.querySelector('article.markdown-body');
        const readmeText = readmeEl ? readmeEl.textContent : '';

        let aiMatch = metaText.match(REPO_TEXT_AI_PATTERNS) || readmeText.match(REPO_TEXT_AI_PATTERNS);
        if (aiMatch) {
            addLog(`[HIT] Explicit AI text: "${aiMatch[0]}"`, false);
            hits.push({ source: 'Documentation', matchedText: aiMatch[0] });
        }

        return hits;
    }

    async function checkRepository(owner, repo) {
        scriptLogs.length = 0;
        addLog(`=== STARTING DEEP SCAN: ${owner}/${repo} ===`, false);

        const reasons = [];
        const flaggedContributors = new Set();

        // 1. Text Check (Immediate DOM)
        const docHits = scanDocumentationText();
        if (docHits.length > 0) {
            const hit = docHits[0];
            reasons.push({ category: 'DOCUMENTATION', title: 'Explicit AI Disclosure', detail: `Found self-reported AI generation phrase: <em>"${escapeHtml(hit.matchedText)}"</em>` });
        }

        // 2. Fire async DOM poller and background API fetches concurrently
        const [domContributors, apiContributors, contents, workflows, commits] = await Promise.all([
            pollDOMForBots(),
            fetchAPI(`repos/${owner}/${repo}/contributors?per_page=100`),
            fetchAPI(`repos/${owner}/${repo}/contents`),
            fetchAPI(`repos/${owner}/${repo}/contents/.github/workflows`),
            fetchAPI(`repos/${owner}/${repo}/commits?per_page=35`)
        ]);

        // Evaluate Polled DOM Results
        const foundUIAgents = [];
        domContributors.forEach(name => {
            if (!flaggedContributors.has(name.toLowerCase())) {
                foundUIAgents.push(`<code>${escapeHtml(name)}</code>`);
                flaggedContributors.add(name.toLowerCase());
            }
        });
        if (foundUIAgents.length > 0) {
            reasons.push({ category: 'CONTRIBUTORS', title: 'AI Agent Contributor', detail: `Found in contributor list: ${foundUIAgents.join(', ')}.` });
        }

        // Evaluate API Contributors
        const foundAPIAgents = [];
        if (Array.isArray(apiContributors)) {
            apiContributors.forEach(user => {
                const match = user.login.match(AI_ENTITY_FLEX);
                if (match && !['github'].includes(match[1].toLowerCase()) && !flaggedContributors.has(match[1].toLowerCase())) {
                    foundAPIAgents.push(`<code>${escapeHtml(user.login)}</code>`);
                    flaggedContributors.add(match[1].toLowerCase());
                }
            });
            if (foundAPIAgents.length > 0) {
                reasons.push({ category: 'CONTRIBUTORS', title: 'AI Contributor Account', detail: `Official API lists bot accounts: ${foundAPIAgents.join(', ')}.` });
            }
        }

        // Evaluate Files (Aggregated)
        if (Array.isArray(contents)) {
            const foundFiles = [];
            contents.forEach(file => {
                AGENT_CONFIGS.forEach(agent => {
                    if (agent.regex.test(file.name)) {
                        foundFiles.push(`<code>${escapeHtml(file.name)}</code> (${agent.name})`);
                    }
                });
            });
            if (foundFiles.length > 0) {
                addLog(`[HIT] Found ${foundFiles.length} config files.`, false);
                reasons.push({ category: 'FILES', title: 'AI Configuration Files Found', detail: `Repository configures AI assistants via: ${foundFiles.join(', ')}.` });
            }
        }

        // Evaluate Workflows (Aggregated)
        if (Array.isArray(workflows)) {
            const foundWfs = [];
            workflows.forEach(wf => {
                if (AI_ENTITY_FLEX.test(wf.name)) {
                    foundWfs.push(`<code>${escapeHtml(wf.name)}</code>`);
                }
            });
            if (foundWfs.length > 0) {
                addLog(`[HIT] Found ${foundWfs.length} AI workflows.`, false);
                reasons.push({ category: 'AUTOMATION', title: 'AI Review Workflows', detail: `GitHub Actions configured for automated code review: ${foundWfs.join(', ')}.` });
            }
        }

        // Evaluate Commits (Aggregated Signatures & Authors)
        if (Array.isArray(commits)) {
            const signatureHits = [];
            const authorHits = new Set();

            for (const c of commits) {
                const msg = c.commit?.message || '';
                const ident = c.author?.login || c.commit?.author?.name || '';

                const identMatch = ident.match(AI_ENTITY_FLEX);
                if (identMatch && !['github'].includes(identMatch[1].toLowerCase())) {
                    const matchedName = identMatch[1].toLowerCase();
                    if (!flaggedContributors.has(matchedName)) {
                        authorHits.add(ident);
                        flaggedContributors.add(matchedName);
                    }
                }

                if (COMMIT_SIG_PATTERNS.test(msg)) {
                    const firstLine = msg.split('\n')[0].slice(0, 60);
                    signatureHits.push(firstLine);
                }
            }

            if (authorHits.size > 0) {
                const authorsArr = Array.from(authorHits).map(a => `<code>${escapeHtml(a)}</code>`);
                addLog(`[HIT] Found ${authorsArr.length} AI commit authors.`, false);
                reasons.push({ category: 'COMMITS', title: 'AI Commit Authorship', detail: `Recent code pushed directly by AI agents: ${authorsArr.join(', ')}.` });
            }

            if (signatureHits.length > 0) {
                const count = signatureHits.length;
                const limit = 2;
                const examples = signatureHits.slice(0, limit).map(line => `<em>"${escapeHtml(line)}..."</em>`).join(' and ');
                const extra = count > limit ? ` (showing 2 of ${count} occurrences)` : '';

                addLog(`[HIT] Found ${count} AI commit signatures.`, false);
                reasons.push({
                    category: 'COMMITS',
                    title: 'AI Generation Signature',
                    detail: `Found ${count} commit ${count === 1 ? 'message' : 'messages'} containing an LLM credit. ex. ${examples}${extra}.`
                });
            }
        }

        addLog(`=== SCAN COMPLETE ===`, false);
        if (reasons.length > 0) {
            renderBanner(reasons);
        } else {
            addLog('No AI signatures found. Banner suppressed.', false);
        }
    }

    function initScan() {
        const repo = getRepoInfo();
        if (!repo || !repo.isRoot) return;

        const currentRepoKey = `${repo.owner}/${repo.repo}`;
        if (scannedRepo === currentRepoKey) return;
        scannedRepo = currentRepoKey;

        setTimeout(() => checkRepository(repo.owner, repo.repo), 1000);
    }

    initScan();
    document.addEventListener('turbo:render', initScan);
    document.addEventListener('pjax:end', initScan);
})();